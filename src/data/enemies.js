/**
 * Calculates scaled stats for an enemy based on its base configuration, level, and dungeon difficulty multiplier.
 */
export function scaleEnemyStats(baseEnemy, level = 1, rankMultiplier = 1.0) {
  // Level scaling curve: 1 + (level - 1) * 0.12
  const levelMult = 1 + (Math.max(1, level) - 1) * 0.12;
  const rankMult = rankMultiplier || 1.0;

  const maxHp = Math.round(baseEnemy.baseHp * levelMult * rankMult);
  const attack = Math.round(baseEnemy.baseAttack * levelMult * rankMult);
  const defense = Math.round(baseEnemy.baseDefense * (1 + (Math.max(1, level) - 1) * 0.08));
  const xpReward = Math.round(baseEnemy.xpReward * (1 + (level - 1) * 0.15) * rankMult);
  const goldReward = Math.round(baseEnemy.goldReward * (1 + (level - 1) * 0.12) * rankMult);

  return {
    ...baseEnemy,
    level,
    maxHp,
    hp: maxHp,
    attack,
    defense,
    xpReward,
    goldReward
  };
}
